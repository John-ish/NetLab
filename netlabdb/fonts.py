def _figlet(text: str, name: str) -> list[str]:
    try:
        raw = Figlet(font=name, width=1000).renderText(text)
    except Exception:
        return []
    lines = [line.rstrip() for line in raw.split("\n")]
    while lines and not lines[0].strip():
        lines.pop(0)
    while lines and not lines[-1].strip():
        lines.pop()
    if not lines:
        return []
    margin = min(len(line) - len(line.lstrip()) for line in lines if line.strip())
    return [line[margin:] for line in lines]


def render(text: str, font: str) -> list[str]:
    text = text.strip()
    if not text:
        return []
    if font == "plain":
        lines = [" ".join(text.upper())]
    elif font in BUILTIN:
        glyphs, gap = BUILTIN[font]
        chars = [c for c in text.upper() if c in glyphs]
        if not chars:
            return []
        lines = [gap.join(glyphs[c][row] for c in chars) for row in range(len(glyphs["A"]))]
    elif font.startswith("fig:") and Figlet is not None:
        lines = _figlet(text, font[4:])
        if not lines:
            return []
    else:
        return render(text, "block")
    width = max(len(line) for line in lines)
    return [line.ljust(width) for line in lines]


def fit(text: str, font: str, width: int) -> tuple[list[str], str]:
    if not text.strip():
        return [], font
    for candidate in (font, "compact", "plain"):
        lines = render(text, candidate)
        if lines and len(lines[0]) <= width:
            return lines, candidate
    lines = render(text, "plain")
    return [line[:max(1, width)] for line in lines], "plain"